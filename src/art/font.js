export const GW = 5, GH = 7, GAP = 1;

export function textWidth(str, scale = 1) {
  return str.length * (GW + GAP) * scale - GAP * scale;
}

export function drawText(ctx, str, x, y, color = '#2b1b0e', { scale = 1, align = 'left' } = {}) {
  str = String(str).toUpperCase();
  const w = textWidth(str, scale);
  if (align === 'center') x -= Math.floor(w / 2);
  else if (align === 'right') x -= w;
  ctx.fillStyle = color;
  for (const ch of str) {
    const g = G[ch] || G['?'];
    for (let j = 0; j < GH; j++) for (let i = 0; i < GW; i++) {
      if (g[j][i] === '#') ctx.fillRect(x + i * scale, y + j * scale, scale, scale);
    }
    x += (GW + GAP) * scale;
  }
}

// Largest scale (up to maxScale) at which str fits in maxWidth.
export function fitScale(str, maxWidth, maxScale = 3) {
  let s = maxScale;
  while (s > 1 && textWidth(String(str), s) > maxWidth) s--;
  return s;
}
